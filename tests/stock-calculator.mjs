import assert from 'node:assert/strict';
import { stockCalculatorCore as c } from '../src/stock-calculator-core.js';
const stock=c.parseStock([['Баркод','Количество'],['00123','7'],['00123','3'],['00999','2']]);
const orders=c.parseOrders([['Артикул продавца','Размер'],['A','44'],['A','44'],['B','48']]);
const ref=c.parseCatalog([['Артикул продавца','Размер','Баркод'],['A','44','00123'],['B','48','00000']]);
const r=c.calculate(stock,orders,[],ref);
assert.equal(r.summary.stockTotal,12);
assert.equal(r.summary.orderTotal,3);
assert.equal(r.summary.deductedTotal,2);
assert.equal(r.summary.outsideTotal,1);
assert.equal(r.summary.remainingTotal,10);
assert.deepEqual(r.rows,[{barcode:'00123',quantity:8},{barcode:'00999',quantity:2}]);
assert.equal(r.unresolved.length,0);
const missing=c.calculate(stock,[{article:'unknown',size:'52',quantity:1,row:2}],[],[]);
assert.equal(missing.unresolved.length,1);
const short=c.calculate([{barcode:'00123',quantity:1}],[{barcode:'00123',quantity:3}],[],[]);
assert.equal(short.summary.deficitTotal,2);
assert.deepEqual(short.rows,[]);
const bad=c.calculate(stock,[{article:'A',size:'44',quantity:1}], [{article:'A',size:'44',barcode:'00123'},{article:'A',size:'44',barcode:'00999'}],[]);
assert.equal(bad.unresolved.length,1);
console.log('Stock calculator checks passed');
